export const BUCKET_L_STEP = 0.05;
export const BUCKET_C_STEP = 0.02;
export const BUCKET_H_STEP = 12;

export function toSimplified(text) {
  let s = String(text || '');
  for (const [t, j] of TRAD_SIMP_PAIRS) {
    if (s.includes(t)) s = s.split(t).join(j);
  }
  return s;
}

export function normalizeHex(hex) {
  const raw = String(hex || '').trim().replace(/^#/, '');
  if (!/^[0-9a-fA-F]{6}$/.test(raw)) return '#808080';
  return `#${raw.toUpperCase()}`;
}

export function oklabBucketKey(hex) {
  const { l, c, h } = hexToOklch(normalizeHex(hex));
  const lQ = Math.round(l / BUCKET_L_STEP) * BUCKET_L_STEP;
  const cQ = Math.round(c / BUCKET_C_STEP) * BUCKET_C_STEP;
  const hQ = Math.round(h / BUCKET_H_STEP) * BUCKET_H_STEP;
  return `${lQ.toFixed(2)}|${cQ.toFixed(2)}|${hQ}`;
}

function applyModifiers(line, spec) {
  let { l, c, h } = spec;
  for (const [ch, mod] of Object.entries(MODIFIERS)) {
    if (line.includes(ch)) {
      l += mod.dL;
      c = Math.max(0.01, c + mod.dC);
    }
  }
  return { l: Math.max(0.08, Math.min(0.98, l)), c: Math.max(0.01, Math.min(0.2, c)), h };
}

/** @returns {{ token: string, index: number, spec: ColorSpec } | null} */
export function findPrimaryColorToken(line) {
  const s = toSimplified(line).replace(/[，。！？、；：「」『』\s]/g, '');
  let best = null;
  let bestWeight = -1;
  for (const bg of COLOR_BIGRAMS) {
    const idx = s.indexOf(bg.token);
    if (idx >= 0 && bg.token.length >= (best?.token.length || 0)) {
      const w = 10 + bg.token.length;
      if (w > bestWeight) {
        bestWeight = w;
        best = { token: bg.token, index: idx, spec: { l: bg.l, c: bg.c, h: bg.h } };
      }
    }
  }
  if (best) return best;
  for (const ch of COLOR_CHARS) {
    const idx = s.indexOf(ch.token);
    if (idx >= 0) {
      const w = 5;
      if (w > bestWeight) {
        bestWeight = w;
        best = { token: ch.token, index: idx, spec: { l: ch.l, c: ch.c, h: ch.h } };
      }
    }
  }
  return best;
}

